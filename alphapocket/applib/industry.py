def code_of(name: str) -> str | None:
    """行业名 → 申万一级指数代码（数据集键为行业名，取数需代码）。"""
    for code, n in SW_L1.items():
        if n == name:
            return code
    return None


def match_sw_l1(*labels: str | None) -> str | None:
    """把行业描述归一为申万一级行业名；多标签按传入顺序取首个命中。

    例：``match_sw_l1("塑料软包装", "橡胶和塑料制品业")`` → "轻工制造"
    （"包装" 先于 "塑料/橡胶" 命中）；``match_sw_l1("汽车零部件·轮胎")`` → "汽车"。
    """
    for label in labels:
        if not label:
            continue
        for name, kws in _KEYWORDS:
            if any(kw in str(label) for kw in kws):
                return name
    return None
